"""Generate the public SDK, reference and machine contracts; --check never writes."""
from pathlib import Path
import argparse
import hashlib
import json
import re
import sys
ROOT=Path(__file__).resolve().parents[1]
SUPPORT='> 🛟 **Need help or found a bug?** Get support at [support.doodesch.de/modframework](https://support.doodesch.de/modframework).'

def read(path):return json.loads(path.read_text(encoding='utf-8'))
def encoded(data):return json.dumps(data,ensure_ascii=False,indent=2)+'\n'
def lua_literal(value):
    if value is True:return 'true'
    if value is False:return 'false'
    if value is None:return 'nil'
    return json.dumps(value,ensure_ascii=False)
def signature(f):
    params=', '.join(p['name']+('?' if p.get('optional') else '')+': '+p['type'] for p in f['parameters'])
    return f['name']+'('+params+'): '+f['returns']
def validate(c):
    if c.get('schema_version')!=1:raise ValueError('Unsupported API contract schema_version')
    seen=set();caps=set(c['capabilities'])
    for f in c['functions']:
        required={'name','group','parameters','returns','summary','capabilities','since','stability','thread','lifecycle','side_effects','reload','persistence','errors','host_operations','example'}
        if required-set(f):raise ValueError('Incomplete public function '+f.get('name','?')+': '+str(required-set(f)))
        if not re.fullmatch(r'mt2\.[a-z]+\.[a-z_]+',f['name']) or f['name'] in seen:raise ValueError('Invalid or duplicate function '+f['name'])
        seen.add(f['name'])
        if set(f['capabilities'])-caps:raise ValueError('Unknown capability on '+f['name'])
        if not f['name'].startswith('mt2.'+f['group']+'.'):raise ValueError('Function group differs')
        for p in f['parameters']:
            if not {'name','type','description'}<=p.keys():raise ValueError('Incomplete parameter on '+f['name'])
        for kind in [f['returns']]+[p['type'] for p in f['parameters']]:
            unknown=set(re.findall(r'MT2\w+',kind))-set(c['types'])-{'MT2EventName','MT2EventPayload'}
            if unknown:raise ValueError('Unknown public type on '+f['name']+': '+str(unknown))
    if len({e['name'] for e in c['events']})!=len(c['events']):raise ValueError('Duplicate event')

def page(title,body):return '---\ntitle: '+json.dumps(title)+'\n---\n\n<!-- Generated by tools/generate_docs.py. Edit api/contract.json or the linked example. -->\n\n# '+title+'\n\n'+body+'\n'
def schema(c,content=False):
    if content:
        item={'type':'object','required':['id','variant','model','material'],'properties':{k:{'type':'string','minLength':1} for k in ('id','name','variant','model','material')},'additionalProperties':True}
        return {'$schema':'https://json-schema.org/draft/2020-12/schema','$id':'urn:mt2fw:content:'+c['api_version'],'title':'MT2 static content definitions','type':'array','minItems':1,'items':item}
    properties={k:{'type':'string','minLength':1,'maxLength':256} for k in ('id','name','version','api_version','type','entry')}
    properties.update(id={'type':'string','pattern':r'^[a-z][a-z0-9]*(?:\.[a-z0-9][a-z0-9_-]*)+$'},
        type={'enum':['lua','native','content']},entry={'type':'string','minLength':1,'format':'mt2-relative-path'},
        version={'type':'string','format':'semver'},api_version={'type':'string','format':'supported-mt2-api'},
        capabilities={'type':'array','items':{'enum':c['capabilities']}},
        multiplayer={'enum':['local','shared','singleplayer'],'default':'singleplayer'},
        dependencies={'type':'object','propertyNames':{'pattern':r'^[a-z][a-z0-9]*(?:\.[a-z0-9][a-z0-9_-]*)+$'},'additionalProperties':{'type':'string'}})
    return {'$schema':'https://json-schema.org/draft/2020-12/schema','$id':'urn:mt2fw:mod:'+c['api_version'],'title':'MT2 mod manifest',
       'type':'object','required':['id','name','version','api_version','type','entry','capabilities'],'properties':properties,'additionalProperties':True,
       'allOf':[{'if':{'required':['multiplayer'],'properties':{'multiplayer':{'const':'local'}}},'then':{'properties':{'capabilities':{'items':{'not':{'enum':['objects.write','time.write','content']}}}}}}]}

def outputs(c):
    result={}
    groups=sorted({f['group'] for f in c['functions']})
    sdk=['---@meta','---MT2 Mod Framework API '+c['api_version']+'. Generated by tools/generate_docs.py.','---Editor definitions only; not runtime code.','']
    sdk+=['---@alias MT2EventName '+ '|'.join("'"+e['name']+"'" for e in c['events']),
          '---@alias MT2EventPayload '+ '|'.join(sorted({e['payload'] for e in c['events']})), '']
    for name,fields in c['types'].items():
        sdk.append('---@class '+name)
        for key,kind in fields.items():sdk.append('---@field '+key+' '+kind)
        sdk.append('')
    for group in groups:
        class_name='MT2'+('UI' if group=='ui' else group.title());sdk.append('---@class '+class_name)
        for f in c['functions']:
            if f['group']!=group:continue
            params=', '.join(p['name']+('?' if p.get('optional') else '')+':'+p['type'] for p in f['parameters'])
            sdk.append('---@field '+f['name'].split('.')[-1]+' fun('+params+'):'+f['returns']+' '+f['summary'])
        sdk.append('')
    sdk+=['---@class MT2']+['---@field '+g+' MT2'+('UI' if g=='ui' else g.title()) for g in groups]+['---@type MT2','mt2 = {}','']
    result['sdk/mt2.lua']='\n'.join(sdk)
    for directory in sorted((ROOT/'examples').glob('*/.mt2fw')):
        result[directory.relative_to(ROOT).as_posix()+'/mt2.lua']=result['sdk/mt2.lua']
        result[directory.relative_to(ROOT).as_posix()+'/api.json']=encoded(c)
    result['docs/public/api/1.0.0/api.json']=encoded(c)
    result['api/generated/mod.schema.json']=encoded(schema(c))
    result['api/generated/content.schema.json']=encoded(schema(c,True))
    result['docs/public/api/1.0.0/mod.schema.json']=encoded(schema(c))
    result['docs/public/api/1.0.0/content.schema.json']=encoded(schema(c,True))
    index='Public Lua API **'+c['api_version']+'**, native ABI **'+str(c['abi_version'])+'**, framework **'+c['framework_version']+'**.\n\n[Events](events.md) | [Types](types.md) | [Capabilities](capabilities.md) | [Native ABI](native.md) | [Manifests](manifests.md)\n\n'
    for group in groups:
        index+='## '+group+'\n\n'
        for f in c['functions']:
            if f['group']==group:index+='- [`'+f['name']+'`](functions/'+f['name'][4:].replace('.','-')+'.md): '+f['summary']+'\n'
        index+='\n'
    result['docs/reference/index.md']=page('API reference',index)
    for f in c['functions']:
        example=ROOT/f['example']
        if not example.is_file():raise ValueError('Referenced example is missing: '+f['example'])
        body=f['summary']+'\n\n```lua\n'+signature(f)+'\n```\n\n'
        if f['parameters']:
            body+='## Parameters\n\n| Name | Type | Default | Meaning |\n| --- | --- | --- | --- |\n'
            for p in f['parameters']:
                default=lua_literal(p.get('default')) if p.get('optional') else 'Required'
                body+='| `'+p['name']+'` | `'+p['type'].replace('|','\\|')+'` | `'+default+'` | '+p['description']+' |\n'
        body+='\n## Contract\n\n'
        for label,key in [('Returns','returns'),('Thread','thread'),('When to call','lifecycle'),('Effects','side_effects'),('Reload','reload'),('Persistence','persistence')]:body+='- **'+label+':** '+f[key]+'\n'
        body+='- **Capabilities:** '+(', '.join('`'+v+'`' for v in f['capabilities']) or 'None')+'\n- **Since:** '+f['since']+'\n- **Stability:** '+f['stability']+'\n\n## Errors\n\n'+''.join('- '+error+'\n' for error in f['errors'])
        body+='\n## Example\n\nThis complete example is also available under `'+f['example']+'` in the source and SDK documentation bundle. Native effects require the real game.\n\n```lua\n'+example.read_text(encoding='utf-8').rstrip()+'\n```\n'
        result['docs/reference/functions/'+f['name'][4:].replace('.','-')+'.md']=page(f['name'],body)
    body='Subscribe with `mt2.events.on`. Callback errors retain their cause and disable the owner. A failed staged replacement keeps the previous instance.\n\n'
    for e in c['events']:body+='## '+e['name']+'\n\n'+e['summary']+'\n\nPayload: `'+e['payload']+'`. Since '+e['since']+'.\n\n'
    result['docs/reference/events.md']=page('Events',body)
    body='Handles carry a world epoch and an exact string UID. Never convert the UID to a floating-point Lua number.\n\n'
    for name,fields in c['types'].items():
        body+='## '+name+'\n\n| Field | Type |\n| --- | --- |\n'+''.join('| `'+k+'` | `'+v.replace('|','\\|')+'` |\n' for k,v in fields.items())+'\n'
    result['docs/reference/types.md']=page('Types',body)
    body='Capabilities belong in `mod.json`. Local mods cannot declare `objects.write`, `time.write` or `content`. Shared writes remain unavailable until the multiplayer bridge is accepted.\n\n'
    for cap in c['capabilities']:
        body+='## '+cap+'\n\n'+''.join('- [`'+f['name']+'`](functions/'+f['name'][4:].replace('.','-')+'.md)\n' for f in c['functions'] if cap in f['capabilities'])+'\n'
    result['docs/reference/capabilities.md']=page('Capabilities',body)
    header=(ROOT/'include/mt2fw/plugin.h').read_text(encoding='utf-8')
    if '#define MT2FW_ABI_VERSION '+str(c['abi_version'])+'u' not in header:raise ValueError('C ABI version differs from contract')
    body='The supported native boundary is `include/mt2fw/plugin.h`, shown below without a manually duplicated declaration list. No STL objects or exceptions may cross this ABI. Plugins remain loaded until process exit.\n\n'
    body+='Host strings are copied during a request. Callback JSON is borrowed until return. The host and PluginInfo strings remain valid through Shutdown. A size query never executes a mutation; request a sufficiently sized buffer once, then perform the call once.\n\n```c\n'+header.rstrip()+'\n```\n\n'
    body+='## Host JSON operations\n\nLua wrappers use the following operations. `ui.begin` and `ui.end` are native host operations; Lua authors use `mt2.ui.window`. Events use the ABI subscribe/unsubscribe pointers.\n\n'+''.join('- `'+op+'`\n' for op in sorted({op for f in c['functions'] for op in f['host_operations']}))
    result['docs/reference/native.md']=page('Native C ABI',body)
    baseline=ROOT/'api/baselines/1.0.0.json'
    old=read(baseline) if baseline.exists() else {'functions':[]}
    old_by={f['name']:f for f in old['functions']};new_by={f['name']:f for f in c['functions']}
    report={'api_version':c['api_version'],'added':sorted(new_by.keys()-old_by.keys()),'removed':sorted(old_by.keys()-new_by.keys()),
            'changed_signatures':[name for name in sorted(new_by.keys()&old_by.keys()) if any(new_by[name][key]!=old_by[name][key] for key in ('parameters','returns','capabilities','lifecycle'))]}
    result['api/generated/changes.json']=encoded(report)
    result['docs/reference/changes.md']=page('API changes','Baseline: API 1.0.0. Generated comparison covers names, parameter types/default metadata and return signatures; semantic changes require an explicit migration note.\n\n```json\n'+encoded(report).rstrip()+'\n```')
    result['api/generated/exports.json']=encoded(sorted(f['name'][4:] for f in c['functions']))
    from mt2fw.__main__ import build_parser
    parser=build_parser();cli='The helper opens when no command is given. These options are generated from the same argparse parser used by the CLI.\n\n```text\n'+parser.format_help().rstrip()+'\n```\n'
    for action in parser._actions:
        if hasattr(action,'choices') and isinstance(action.choices,dict):
            for name,command in action.choices.items():cli+='\n## '+name+'\n\n```text\n'+command.format_help().rstrip()+'\n```\n'
    cli+='\n`new` creates a complete project. `check` validates it without executing scripts. `pack` writes an archive outside its source. `doctor` reads game/profile diagnostics. Installation commands preserve original game data and require the target game to be closed.\n'
    result['docs/reference/cli.md']=page('Command-line reference',cli)
    return result

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    contract=read(ROOT/'api/contract.json');validate(contract);generated=outputs(contract);stale=[]
    for name,body in generated.items():
        path=ROOT/name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=body:stale.append(name)
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(body,encoding='utf-8')
    if stale:raise ValueError('Generated outputs differ; run python tools/generate_docs.py: '+', '.join(stale))
    print(f'info: {"checked" if args.check else "generated"} {len(generated)} API/SDK outputs from {len(contract["functions"])} functions')
if __name__=='__main__':
    try:main()
    except (OSError,ValueError,KeyError) as error:print('error: '+str(error),file=sys.stderr);sys.exit(1)
